"""Recheck independent bug findings using synthetic samples and isolated data.

Only the files generated by this run are sent to the Windows Recycle Bin.
The supplied report, evidence, and samples are read-only inputs.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import socket
import subprocess
import sys
import time
from urllib.request import Request, urlopen
import uuid

ROOT=Path(__file__).resolve().parents[1]


def main():
    import argparse
    parser=argparse.ArgumentParser()
    parser.add_argument('--samples',type=Path,required=True)
    parser.add_argument('--url',default='',help='Optional already-running isolated packaged service')
    parser.add_argument('--exe',type=Path,help='Start the actual Windows launcher instead of source app.py')
    parser.add_argument('--home',type=Path,help='Isolated test installation to reuse with --exe')
    args=parser.parse_args()
    folder=ROOT/'.local/bugfix25'/('live-'+time.strftime('%Y%m%d-%H%M%S'))
    folder.mkdir(parents=True)
    samples=folder/'samples';samples.mkdir()
    for name in ('main_20s.mp4','truncated.mp4','audio_only_as_mp4.mp4'):
        shutil.copyfile(args.samples/name,samples/name)
    shutil.copyfile(samples/'main_20s.mp4',samples/'second.mp4')
    hashes={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in samples.iterdir()}
    proc=None;stream=None;stop=None;launcher=None;results={'sample_sha256':hashes,'checks':{},'packaged':bool(args.exe)}
    def record(name,value):
        results['checks'][name]=value
        (folder/'results.json').write_text(json.dumps(results,ensure_ascii=False,indent=2),'utf-8')
        print(name+': PASS',flush=True)
    try:
        if args.url:base=args.url.rstrip('/')
        elif args.exe:
            stop=folder/'launcher.stop';report=folder/'launcher.json'
            env={k:v for k,v in os.environ.items() if k.upper() not in ('HTTP_PROXY','HTTPS_PROXY')}
            env.update(PATH=str(Path(os.environ.get('SystemRoot','C:/Windows'))/'System32'),
                HTTP_PROXY='',http_proxy='',HTTPS_PROXY='',https_proxy='',
                PYTHONHOME=str(folder/'missing-python'),PYTHONPATH=str(folder/'missing-site-packages'))
            proc=subprocess.Popen([str(args.exe.resolve()),'--self-test','--home',str((args.home or folder/'app-home').resolve()),
                '--report',str(report),'--stop-file',str(stop)],env=env,creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
            deadline=time.monotonic()+360
            while not report.is_file():
                assert proc.poll() is None,'Launcher exited before report'
                assert time.monotonic()<deadline,'Launcher startup timeout';time.sleep(.1)
            launcher=json.loads(report.read_text('utf-8'));assert launcher['success'],launcher
            base=launcher['url']
            assert (Path(launcher['install'])/'app/app.py').read_text('utf-8')==(ROOT/'app.py').read_text('utf-8'),'Packaged source mismatch'
            record('packaged_startup',{'version':launcher['version'],'duplicate_proxy_names':True,'isolated_system_path':True,'app_source_matches':True})
        else:
            with socket.socket() as sock:sock.bind(('127.0.0.1',0));port=sock.getsockname()[1]
            base=f'http://127.0.0.1:{port}'
            env={**os.environ,'PYTHONUTF8':'1','PYTHONIOENCODING':'utf-8','VIDEO_DESK_PORT':str(port),
                'VIDEO_DESK_DATA':str(folder/'data'),'VIDEO_DESK_DEFAULT_OUTPUT':str(folder/'output'),
                'VIDEO_DESK_NODE_EXE':str(ROOT/'.local/build-exe/payload/runtime/node/node.exe')}
            stream=(folder/'server.log').open('wb')
            proc=subprocess.Popen([sys.executable,str(ROOT/'app.py')],cwd=ROOT,env=env,stdout=stream,stderr=stream)
        for _ in range(200):
            try:
                with urlopen(base+'/api/state',timeout=1) as response:token=json.load(response)['token']
                break
            except OSError:
                if proc:assert proc.poll() is None,'Service exited'
                time.sleep(.1)
        else:raise AssertionError('Service startup timed out')
        def api(path,body=None):
            with urlopen(Request(base+path,data=None if body is None else json.dumps(body).encode(),
                headers={'X-App-Token':token,'Content-Type':'application/json'}),timeout=90) as response:return json.load(response)
        source_rows=api('/api/sources/register',{'paths':[str(p) for p in samples.iterdir()]})['sources']
        deadline=time.monotonic()+60
        while True:
            rows={s['id']:s for s in api('/api/sources')['sources']}
            if all(rows[s['id']]['status']!='validating' for s in source_rows):break
            assert time.monotonic()<deadline,'Source validation timeout';time.sleep(.1)
        sources={s['name']:rows[s['id']] for s in source_rows}
        good=sources['main_20s.mp4']['id'];bad=sources['truncated.mp4']['id']
        def create(ids=None,kind='rules',**extra):
            return api('/api/batches',{'sources':ids or [good],'kind':kind,'workflow':kind,'output':str(folder/'output'),
                'performance':'balanced','outputs':{'frames':True},'frames':{'mode':'seconds','value':3,'audio':False},
                'request_id':uuid.uuid4().hex,**extra})
        def wait(jid):
            deadline=time.monotonic()+180
            while time.monotonic()<deadline:
                row=api('/api/batches/'+jid)
                if row['job']['status'] in ('done','error','cancelled'):
                    (folder/(jid+'.json')).write_text(json.dumps(row,ensure_ascii=False,indent=2),'utf-8')
                    return row
                time.sleep(.1)
            raise AssertionError('Batch timeout: '+jid)
        for seconds,count in ((3,7),(5,4)):
            row=wait(create(frames={'mode':'seconds','value':seconds,'audio':False})['id'])
            child=row['children'][0]
            assert row['job']['status']=='done',row
            assert child['frames']==count,(count,child)
            record('healthy_'+str(seconds)+'s',{'frames':count,'status':row['job']['status']})
            if seconds==3:regeneration_base=row['job']
            row=wait(create(ids=[bad],frames={'mode':'seconds','value':seconds,'audio':False})['id'])
            child=row['children'][0]
            assert row['job']['status']=='error',row
            assert child['source_diagnostic']['category']=='incomplete_media',child
            record('VD25-02_'+str(seconds)+'s',{'status':row['job']['status'],'diagnostic':child['source_diagnostic']})
        replaced=wait(api('/api/exports/'+regeneration_base['id'],{'replace_job_id':regeneration_base['id'],
            'frames':{'mode':'seconds','value':5,'audio':False},'request_id':uuid.uuid4().hex})['id'])
        assert replaced['job']['status']=='done' and '已覆盖' in replaced['job']['replacement_note'],replaced
        assert replaced['job']['directory']==regeneration_base['directory']
        personal=Path(replaced['children'][0]['directory'])/'personal.txt';personal.write_text('Keep my note.','utf-8')
        preserved=wait(api('/api/exports/'+replaced['job']['id'],{'replace_job_id':replaced['job']['id'],
            'frames':{'mode':'seconds','value':3,'audio':False},'request_id':uuid.uuid4().hex})['id'])
        assert preserved['job']['status']=='done' and '另存' in preserved['job']['replacement_note'],preserved
        assert personal.read_text('utf-8')=='Keep my note.'
        record('VD25-01_regeneration',{'verified_outputs_replaced':True,'personal_file_forces_separate_output':True})
        row=wait(create(ids=[good,sources['audio_only_as_mp4.mp4']['id']])['id'])
        assert row['job']['status']=='error' and row['job']['progress']==50,row
        assert {c['status'] for c in row['children']}=={'done','error'},row
        record('VD25-03_failure',{'status':row['job']['status'],'progress':row['job']['progress'],'counts':row['job']['counts']})
        parent=create(ids=[good,sources['second.mp4']['id']],frames={'mode':'all','audio':False,'limit':500})
        deadline=time.monotonic()+30
        while True:
            row=api('/api/batches/'+parent['id'])
            if len(row['children'])==2:break
            assert time.monotonic()<deadline;time.sleep(.02)
        api('/api/jobs/'+row['children'][1]['id']+'/cancel',{})
        row=wait(parent['id'])
        assert row['job']['status']=='cancelled' and row['job']['progress']==50,row
        record('VD25-03_cancelled',{'status':row['job']['status'],'progress':row['job']['progress'],'counts':row['job']['counts']})
        row=wait(create(ids=[good,sources['second.mp4']['id']],frames={'mode':'seconds','value':5,'audio':False})['id'])
        first,second=row['children'];locked=next((Path(second['directory'])/'frames').glob('*.jpg'))
        if os.name=='nt':
            import ctypes
            kernel=ctypes.WinDLL('kernel32',use_last_error=True)
            kernel.CreateFileW.argtypes=[ctypes.c_wchar_p,ctypes.c_uint,ctypes.c_uint,ctypes.c_void_p,ctypes.c_uint,ctypes.c_uint,ctypes.c_void_p]
            kernel.CreateFileW.restype=ctypes.c_void_p
            kernel.CloseHandle.argtypes=[ctypes.c_void_p]
            handle=kernel.CreateFileW(str(locked),0x80000000,1,None,3,0,None)
            assert handle not in (None,ctypes.c_void_p(-1).value),ctypes.get_last_error()
            try:
                expected_one=len(api('/api/materials/'+first['id']+'/cleanup')['files'])
                expected_two=len(api('/api/materials/'+second['id']+'/cleanup')['files'])
                cleanup=api('/api/materials/cleanup-batch',{'ids':[first['id'],second['id']]})
                assert cleanup['deleted']==expected_one+expected_two-1 and len(cleanup['errors'])==1,cleanup
                after=api('/api/batches/'+row['job']['id'])['children']
                one=next(c for c in after if c['id']==first['id']);two=next(c for c in after if c['id']==second['id'])
                assert one['material_cleanup']['deleted']==expected_one and not one['material_cleanup']['errors'] and one['materials_deleted'],one
                assert two['material_cleanup']['deleted']==expected_two-1 and len(two['material_cleanup']['errors'])==1 and not two['materials_deleted'],two
                assert locked.is_file()
                record('VD25-05_and_06_locked_file',{'first':one['material_cleanup'],'second':two['material_cleanup'],
                    'locked_file_preserved':True,'global_deleted':cleanup['deleted']})
            finally:kernel.CloseHandle(handle)
        parent=create(frames={'mode':'all','audio':False,'limit':500})
        row=api('/api/batches/'+parent['id']);child=row['children'][0]
        assert child['status'] not in ('done','error','cancelled'),'Injection was too late'
        note=Path(child['directory'])/'MY-NOTE-DO-NOT-DELETE.txt';note.write_text('Personal note injected while processing.','utf-8')
        note_hash=hashlib.sha256(note.read_bytes()).hexdigest()
        row=wait(parent['id']);assert row['job']['status']=='done',row
        preview=api('/api/materials/cleanup-preview',{'ids':[parent['id']]})
        assert sum(p['name'].endswith('.jpg') for p in preview['files'])==500,preview
        assert not any(p['path']==str(note) for p in preview['files']),preview
        assert any(p['name'].endswith(note.name) for p in preview['skipped']),preview
        cleanup=api('/api/materials/cleanup-batch',{'ids':[parent['id']]})
        assert cleanup['deleted']==len(preview['files']) and not cleanup['errors'],cleanup
        assert hashlib.sha256(note.read_bytes()).hexdigest()==note_hash
        assert not list(note.parent.rglob('*.jpg'))
        (folder/'cleanup.json').write_text(json.dumps({'preview':preview,'result':cleanup},ensure_ascii=False,indent=2),'utf-8')
        record('VD25-01_and_05_live_recycle',{'injected_during_processing':True,'note_sha256':note_hash,
            'note_preserved':True,'generated_files_recycled':cleanup['deleted'],'warnings':cleanup['warnings']})
        from playwright.sync_api import sync_playwright,expect
        chrome=next((ROOT/'.local/build-exe/payload/runtime/browsers').glob('chromium-*/chrome-win64/chrome.exe'))
        errors=[]
        with sync_playwright() as playwright:
            browser=playwright.chromium.launch(executable_path=str(chrome),headless=True)
            page=browser.new_page(viewport={'width':1440,'height':1100})
            page.on('pageerror',lambda error:errors.append(str(error)))
            page.goto(base);page.wait_for_function('serverSettingsLoaded')
            page.evaluate("source=>{localSources=[source];renderLocalSources();goto('subtitles')}",sources['main_20s.mp4'])
            page.locator('#subtitleStartTime').fill('10');page.locator('#subtitleDuration').fill('5')
            page.locator('#subtitleDuration').blur()
            with page.expect_response(lambda r:r.url.endswith('/api/batches') and r.request.method=='POST') as submitted:
                page.locator('#subtitleStart').click()
            response=submitted.value;body=response.request.post_data_json
            assert body['analysis']['start']==10 and body['analysis']['duration']==5,body
            row=wait(response.json()['id']);child=row['children'][0]
            assert row['job']['status']=='done',row
            assert child['segments'][0]['from']==10 and child['segments'][0]['to']==15,child
            page.reload();page.wait_for_function('serverSettingsLoaded');page.locator('[data-page="subtitles"]').click()
            expect(page.locator('#subtitleStartTime')).to_have_value('10')
            expect(page.locator('#subtitleDuration')).to_have_value('5')
            page.screenshot(path=str(folder/'subtitle-range.png'),full_page=True)
            assert not errors,errors
            record('VD25-07_browser',{'request_start':10,'request_duration':5,'actual_segments':child['segments'],
                'settings_survived_reload':True,'browser_errors':errors})
            browser.close()
        assert hashes=={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in samples.iterdir()}
        record('synthetic_inputs_unchanged',True)
        if launcher:
            test_env={**os.environ,'VIDEO_DESK_URL':base,'VIDEO_DESK_TEST_VIDEO':str(samples/'main_20s.mp4'),'VIDEO_DESK_TEST_OUTPUT':str(folder/'dsh-output')}
            with (folder/'dsh.log').open('wb') as log:
                subprocess.run([launcher['node'],'--test',str(ROOT/'tests/test_dsh_adapter.mjs')],env=test_env,stdout=log,stderr=log,timeout=120,check=True)
            record('actual_runtime_DSH',{'passed':2})
        print('Evidence: '+str(folder),flush=True)
    finally:
        if proc:
            if stop:stop.write_text('stop','ascii')
            else:proc.terminate()
            try:proc.wait(timeout=30)
            except subprocess.TimeoutExpired:proc.kill();proc.wait()
        if stream:stream.close()


if __name__=='__main__':main()
